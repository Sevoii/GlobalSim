"""Write js/src/catalog.ts from the generated Python catalog.

The Python modules (python/globalsim/enums.py and courses.py, written by
generate_catalog.py) are the single source, so both packages carry identical
members, labels, course table and presets. generate_catalog.py calls this after
regenerating; run it directly after editing those modules by hand.
"""
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / 'python/globalsim'
OUTPUT = ROOT / 'js/src/catalog.ts'


def load(name):
    # Load by path: importing the globalsim package would require the compiled extension.
    spec = importlib.util.spec_from_file_location(f'_catalog_{name}', PACKAGE / f'{name}.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def literal(value):
    return json.dumps(value, ensure_ascii=False)


def members(name, enum):
    lines = [f'export const {name} = {{']
    lines += [f'  {member.name}: {literal(member.value)},' for member in enum]
    lines += ['} as const;', f'export type {name} = (typeof {name})[keyof typeof {name}];', '']
    return lines


def table(name, value_type, items):
    lines = [f'export const {name}: Readonly<Record<{value_type}>> = {{']
    lines += [f'  {literal(key) if isinstance(key, str) else key}: {literal(value)},' for key, value in items]
    return lines + ['};', '']


def render():
    enums, courses = load('enums'), load('courses')
    lines = ['// Generated by tools/generate_js_catalog.py from python/globalsim/enums.py and',
             '// courses.py (alpha123/uma-tools and GlobalSim data; see CATALOG-SOURCES.md). Do not edit.',
             '/* eslint-disable */', '']
    lines += members('Skill', enums.Skill)
    lines += table('SKILL_LABELS', 'number, string', sorted(enums._SKILL_LABELS.items()))
    lines += members('Uma', enums.Uma)
    lines += table('UMA_LABELS', 'number, string', sorted(enums._UMA_LABELS.items()))
    lines += members('Track', courses.Track)
    lines += table('TRACK_LABELS', 'number, string', sorted(courses._TRACK_LABELS.items()))
    lines += members('ChampionsMeeting', courses.ChampionsMeeting)
    lines += table('CHAMPIONS_MEETING_LABELS', 'string, string',
                   sorted(courses._CHAMPIONSMEETING_LABELS.items()))
    lines += ['/** courseId: [raceTrackId, surface, distance, distanceType, layout, turn] */']
    lines += table('COURSES', 'number, readonly [number, number, number, number, number, number]',
                   sorted(courses._COURSES.items()))
    lines += ["/** Global Champions Meeting presets. Conditions use the engine's JP-derived names,",
              " * e.g. ground 'Good' is Global Firm. value: [date, courseId, season, ground, weather, time] */"]
    lines += table('CHAMPIONS_MEETINGS', 'string, readonly [string, number, string, string, string, string]',
                   courses._CHAMPIONS_MEETINGS.items())
    ids = sorted(enums._BUNDLED_SKILL_IDS)
    lines += ['/** Skill IDs defined by the bundled (fallback) engine table, data/skill_data.json. */',
              'export const BUNDLED_SKILL_IDS: ReadonlySet<number> = new Set([',
              *('  ' + ', '.join(map(str, ids[i:i + 8])) + ',' for i in range(0, len(ids), 8)), ']);', '']
    return '\n'.join(lines)


def write():
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render(), encoding='utf-8', newline='\n')


if __name__ == '__main__':
    write()
    print(f'Wrote {OUTPUT.relative_to(ROOT)}')
